"use strict";

var fs = require("fs");
var path = require("path");

var rootDir = __dirname;
var levelsDir = path.join(rootDir, "Levels");
var manifestPath = path.join(levelsDir, "manifest.json");
var tutorialsDir = path.join(rootDir, "Tutorials");
var tutorialManifestPath = path.join(tutorialsDir, "manifest.json");
var elementRunDir = path.join(rootDir, "ElementRun");
var elementRunManifestPath = path.join(elementRunDir, "manifest.json");
var bonusDir = path.join(rootDir, "BonusLevels");
var bonusManifestPath = path.join(bonusDir, "manifest.json");
var outputPath = path.join(rootDir, "levels-inline.js");

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function hashString(input) {
  var hash = 2166136261;
  for (var i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(16);
}

function buildProjectHash(manifest, levels) {
  return hashString(JSON.stringify({ manifest: manifest, levels: levels }));
}

function readLevelSet(dir, setManifestPath, label) {
  if (!fs.existsSync(setManifestPath)) {
    throw new Error("Missing " + label + " manifest: " + setManifestPath);
  }

  var manifest = readJson(setManifestPath);
  if (!Array.isArray(manifest) || !manifest.length) {
    throw new Error(label + " manifest must be a non-empty array of filenames.");
  }

  var levels = manifest.map(function(fileName) {
    var fullPath = path.join(dir, fileName);
    if (!fs.existsSync(fullPath)) {
      throw new Error("Missing " + label + " file: " + fileName);
    }

    var level = readJson(fullPath);
    if (!Array.isArray(level.grid)) {
      throw new Error(label + " file has no grid: " + fileName);
    }
    if (typeof level.cols !== "number" || typeof level.rows !== "number") {
      throw new Error(label + " file has invalid dimensions: " + fileName);
    }
    return level;
  });

  return { manifest: manifest, levels: levels };
}

function buildInlineBundle() {
  var missions = readLevelSet(levelsDir, manifestPath, "Mission");

  // Tutorials and the element run are optional - bundle them when their folders exist
  var tutorials = { manifest: [], levels: [] };
  if (fs.existsSync(tutorialManifestPath)) {
    tutorials = readLevelSet(tutorialsDir, tutorialManifestPath, "Tutorial");
  }
  var elementRun = { manifest: [], levels: [] };
  if (fs.existsSync(elementRunManifestPath)) {
    elementRun = readLevelSet(elementRunDir, elementRunManifestPath, "ElementRun");
  }
  // Bonus missions ship only in the paid build - the dist script excludes the
  // BonusLevels/ folder for the free build and this block then bundles nothing
  var bonus = { manifest: [], levels: [] };
  if (fs.existsSync(bonusManifestPath)) {
    bonus = readLevelSet(bonusDir, bonusManifestPath, "Bonus");
  }

  var allManifests = missions.manifest.concat(tutorials.manifest, elementRun.manifest, bonus.manifest);
  var allLevels = missions.levels.concat(tutorials.levels, elementRun.levels, bonus.levels);
  var meta = {
    generatedAt: new Date().toISOString(),
    projectHash: buildProjectHash(allManifests, allLevels)
  };

  var content = '"use strict";\n\n' +
    "// GENERATED by generate-levels-inline.js - do not edit by hand.\n" +
    "// The levels are content under CC BY-NC-SA 4.0, not the MIT License - see LICENSE-CONTENT.md.\n" +
    "window.__MISSION_MANIFEST__ = " + JSON.stringify(missions.manifest, null, 2) + ";\n" +
    "window.__MISSION_LEVELS__ = " + JSON.stringify(missions.levels, null, 2) + ";\n" +
    "window.__TUTORIAL_MANIFEST__ = " + JSON.stringify(tutorials.manifest, null, 2) + ";\n" +
    "window.__TUTORIAL_LEVELS__ = " + JSON.stringify(tutorials.levels, null, 2) + ";\n" +
    "window.__ELEMENTRUN_MANIFEST__ = " + JSON.stringify(elementRun.manifest, null, 2) + ";\n" +
    "window.__ELEMENTRUN_LEVELS__ = " + JSON.stringify(elementRun.levels, null, 2) + ";\n" +
    "window.__BONUS_MANIFEST__ = " + JSON.stringify(bonus.manifest, null, 2) + ";\n" +
    "window.__BONUS_LEVELS__ = " + JSON.stringify(bonus.levels, null, 2) + ";\n" +
    "window.__MISSION_BUNDLE_META__ = " + JSON.stringify(meta, null, 2) + ";\n";

  fs.writeFileSync(outputPath, content);
  return { count: missions.levels.length, tutorialCount: tutorials.levels.length, elementRunCount: elementRun.levels.length, bonusCount: bonus.levels.length, outputPath: outputPath };
}

module.exports = {
  buildInlineBundle: buildInlineBundle,
  paths: {
    rootDir: rootDir,
    levelsDir: levelsDir,
    manifestPath: manifestPath,
    tutorialsDir: tutorialsDir,
    tutorialManifestPath: tutorialManifestPath,
    outputPath: outputPath
  },
  buildProjectHash: buildProjectHash
};

if (require.main === module) {
  try {
    var result = buildInlineBundle();
    console.log("Rebuilt local mission bundle with " + result.count + " levels + " + result.tutorialCount + " tutorials + " + result.elementRunCount + " element run + " + result.bonusCount + " bonus:");
    console.log(result.outputPath);
  } catch (err) {
    console.error(err && err.message ? err.message : err);
    process.exit(1);
  }
}