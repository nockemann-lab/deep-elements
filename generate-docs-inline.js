"use strict";

// Bundles the three documents the game can show (sources, teacher's guide,
// credits) into docs-inline.js, so they open inside the game even when it is
// run straight from a folder. Re-run after editing any of the three files:
//   node generate-docs-inline.js

var fs = require("fs");
var path = require("path");

var docs = { sources: "SOURCES.md", guide: "TEACHERS_GUIDE.md", credits: "CREDITS.md" };
var out = {};
Object.keys(docs).forEach(function(key) {
  out[key] = fs.readFileSync(path.join(__dirname, docs[key]), "utf8");
});
fs.writeFileSync(path.join(__dirname, "docs-inline.js"),
  '"use strict";\n\n// GENERATED by generate-docs-inline.js - do not edit by hand.\n// The documents are content under CC BY-NC-SA 4.0, not the MIT License - see LICENSE-CONTENT.md.\nwindow.__DOCS__ = ' + JSON.stringify(out, null, 2) + ";\n");
console.log("Wrote docs-inline.js");
